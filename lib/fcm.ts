import api from "@/lib/axios";

export async function ensureFcmTokenSync(userObj?: any): Promise<string | null> {
  if (typeof window === "undefined") return null;

  try {
    const storedFcmToken = localStorage.getItem("fcm_token");
    const storedUserRaw = localStorage.getItem("user");
    let currentUser = userObj;

    if (!currentUser && storedUserRaw) {
      try {
        currentUser = JSON.parse(storedUserRaw);
      } catch (e) {}
    }

    const existingFcmToken = currentUser?.fcm_token || storedFcmToken;

    // Reject pseudo fallback tokens starting with "fcm_"
    const isValidRealToken =
      existingFcmToken && !existingFcmToken.startsWith("fcm_");

    if (isValidRealToken) {
      if (!storedFcmToken && existingFcmToken) {
        localStorage.setItem("fcm_token", existingFcmToken);
      }
      return existingFcmToken;
    }

    // If browser doesn't support Notification, return null
    if (!("Notification" in window) || !("serviceWorker" in navigator)) {
      console.warn("Notification or Service Worker API not supported in this browser.");
      return null;
    }

    // Request browser notification permission
    const permission = await Notification.requestPermission();
    if (permission !== "granted") {
      console.warn("User did not grant notification permission:", permission);
      return null;
    }

    let fcmToken: string | null = null;

    try {
      // Register Firebase Messaging Service Worker with env config params
      const swParams = new URLSearchParams({
        apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || "",
        authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || "",
        databaseURL: process.env.NEXT_PUBLIC_FIREBASE_DATABASE_URL || "",
        projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "",
        storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || "",
        messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
        appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || "",
        measurementId: process.env.NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID || "",
      });
      const registration = await navigator.serviceWorker.register(
        `/firebase-messaging-sw.js?${swParams.toString()}`
      );

      const { getMessaging, getToken, isSupported } = await import("firebase/messaging");
      const { app } = await import("@/lib/firebase");

      const supported = await isSupported();
      if (supported && app) {
        const messaging = getMessaging(app);
        const vapidKey = process.env.NEXT_PUBLIC_FIREBASE_VAPID_KEY;

        fcmToken = await getToken(messaging, {
          serviceWorkerRegistration: registration,
          ...(vapidKey ? { vapidKey } : {}),
        });
      }
    } catch (fcmErr) {
      console.error("Error retrieving genuine FCM registration token:", fcmErr);
    }

    // If no valid FCM token was generated, do NOT generate pseudo strings
    if (!fcmToken) {
      console.warn("No valid FCM token generated by Firebase Messaging.");
      return null;
    }

    // Save authentic FCM token in localStorage
    localStorage.setItem("fcm_token", fcmToken);

    // Update user object in localStorage
    if (storedUserRaw) {
      try {
        const parsed = JSON.parse(storedUserRaw);
        parsed.fcm_token = fcmToken;
        localStorage.setItem("user", JSON.stringify(parsed));
      } catch (e) {}
    }

    // Update user via API "auth/fcm_token"
    try {
      await api.post("/auth/fcm_token", { fcm_token: fcmToken });
    } catch (err1: any) {
      try {
        await api.put("/auth/fcm_token", { fcm_token: fcmToken });
      } catch (err2: any) {
        try {
          await api.post("/auth/fcm_token", { token: fcmToken });
        } catch (err3) {
          console.warn("Failed to send fcm_token to /auth/fcm_token API:", err3);
        }
      }
    }

    return fcmToken;
  } catch (error) {
    console.error("Error in ensureFcmTokenSync:", error);
    return null;
  }
}
